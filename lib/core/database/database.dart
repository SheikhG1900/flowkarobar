      ('US Dollar', '\$', 'USD', 2),
      ('Indian Rupee', '₹', 'INR', 0),
      ('Pakistani Rupee', 'Rs.', 'PKR', 0),
    ];

    for (final curr in defaultCurrencies) {
      await into(appCurrencies).insert(
        AppCurrenciesCompanion.insert(
          uuid: uuid.v4(),
          name: curr.$1,
          symbol: curr.$2,
          code: curr.$3,
          decimalPlaces: Value(curr.$4),
          isDefault: const Value(true),
        ),
      );
