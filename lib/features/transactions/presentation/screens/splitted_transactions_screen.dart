import 'package:flowpaisa/core/theme/app_colors.dart';
import 'package:flowpaisa/core/utils/amount_formatter.dart';
import 'package:flowpaisa/features/transactions/domain/models.dart';
import 'package:flowpaisa/features/transactions/presentation/providers/transactions_provider.dart';
import 'package:flowpaisa/features/transactions/presentation/utils/split_share_settled_label.dart';
import 'package:flowpaisa/features/transactions/presentation/widgets/transaction_details_dialog.dart';
import 'package:flowpaisa/features/transactions/presentation/screens/edit_split_transaction_screen.dart';
import 'package:flowpaisa/l10n/app_localizations.dart';
import 'package:flowpaisa/shared/providers/currency_provider.dart';
import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';

class SplittedTransactionsScreen extends ConsumerWidget {
  final String transactionUuid;

  const SplittedTransactionsScreen({
    super.key,
    required this.transactionUuid,
  });

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final l10n = AppLocalizations.of(context)!;
    final groupAsync = ref.watch(transactionGroupProvider(transactionUuid));
    final currencyAsync = ref.watch(currentCurrencyProvider);
    final currency = currencyAsync.value;

    return Scaffold(
      appBar: AppBar(
        title: Text(l10n.splittedTransactions),
        actions: [
          groupAsync.when(
            data: (group) {
              final first = group.firstOrNull;
              if (first == null) return const SizedBox.shrink();
              final isSettled = first.isLinkedEntryMarked;
              final isAuto = first.transaction.isAutoGenerated;
              if (isSettled || isAuto) return const SizedBox.shrink();

              return IconButton(
                icon: const Icon(Icons.splitscreen),
                onPressed: () {
                  Navigator.push(
                    context,
                    MaterialPageRoute(
                      builder: (context) => EditSplitTransactionScreen(
                        transactionUuid: transactionUuid,
                      ),
                    ),
                  );
                },
              );
            },
            loading: () => const SizedBox.shrink(),
            error: (_, __) => const SizedBox.shrink(),
          ),
        ],
      ),
      body: groupAsync.when(
        data: (group) {
          if (group.isEmpty) {
            return Center(child: Text(l10n.noTransactionsFound));
          }
          if (currency == null) {
            return const Center(child: CircularProgressIndicator());
          }

          return Column(
            children: [
              _buildSummaryCard(context, group, currency),
              Expanded(
                child: ListView.builder(
                  padding: const EdgeInsets.all(16),
                  itemCount: group.length,
                  itemBuilder: (context, index) {
                    final sibling = group[index];
                    return _buildSiblingCard(context, ref, sibling, currency);
                  },
                ),
              ),
            ],
          );
        },
        loading: () => const Center(child: CircularProgressIndicator()),
        error: (err, _) => Center(child: Text(l10n.errorOccurred(err.toString()))),
      ),
    );
  }

  Widget _buildSummaryCard(
      BuildContext context, List<TransactionWithDetails> group, dynamic currency) {
    final l10n = AppLocalizations.of(context)!;
    final theme = Theme.of(context);

    double totalAmount = 0;
    double paidAmount = 0;
    double receivedAmount = 0;
    double pendingAmount = 0;
    bool hasPayables = false;
    bool hasReceivables = false;

    for (final item in group) {
      totalAmount += item.transaction.amount;
      if (item.linkedPayable != null) {
        hasPayables = true;
        if (item.linkedPayable!.status == 'PAID') {
          paidAmount += item.transaction.amount;
        } else {
          pendingAmount += item.transaction.amount;
        }
      } else if (item.linkedReceivable != null) {
        hasReceivables = true;
        if (item.linkedReceivable!.status == 'RECEIVED') {
          receivedAmount += item.transaction.amount;
        } else {
          pendingAmount += item.transaction.amount;
        }
      }
    }

    return Container(
      width: double.infinity,
      margin: const EdgeInsets.all(16),
      padding: const EdgeInsets.all(20),
      decoration: BoxDecoration(
        color: theme.colorScheme.primaryContainer.withValues(alpha: 0.3),
        borderRadius: BorderRadius.circular(20),
        border: Border.all(color: theme.colorScheme.primary.withValues(alpha: 0.2)),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Text(
            l10n.summary,
            style: theme.textTheme.titleMedium?.copyWith(fontWeight: FontWeight.bold),
          ),
          const SizedBox(height: 16),
          Row(
            mainAxisAlignment: MainAxisAlignment.spaceBetween,
            children: [
              _buildSummaryItem(context, l10n.totalAmount, totalAmount, currency, theme.colorScheme.primary),
              _buildSummaryItem(context, l10n.balance, totalAmount - paidAmount - receivedAmount, currency, theme.colorScheme.secondary),
            ],
          ),
          const Divider(height: 32),
          Row(
            mainAxisAlignment: MainAxisAlignment.spaceBetween,
            children: [
              if (hasPayables)
                _buildSummaryItem(context, l10n.paid, paidAmount, currency, AppColors.expenseColor),
              if (hasReceivables)
                _buildSummaryItem(context, l10n.received, receivedAmount, currency, AppColors.incomeColor),
              _buildSummaryItem(context, l10n.pending, pendingAmount, currency, Colors.orange),
            ],
          ),
        ],
      ),
    );
  }

  Widget _buildSummaryItem(BuildContext context, String label, double amount,
      dynamic currency, Color color) {
    final theme = Theme.of(context);
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Text(label, style: theme.textTheme.bodySmall),
        const SizedBox(height: 4),
        Text(
          AmountFormatter.formatWithCurrency(amount, currency.symbol, currency.decimalPlaces),
          style: theme.textTheme.titleMedium?.copyWith(
            fontWeight: FontWeight.bold,
            color: color,
          ),
        ),
      ],
    );
  }

  Widget _buildSiblingCard(BuildContext context, WidgetRef ref,
      TransactionWithDetails sibling, dynamic currency) {
    final l10n = AppLocalizations.of(context)!;
    final theme = Theme.of(context);

    final isUserShare = sibling.transaction.contactUuid == null;
    final label = isUserShare ? l10n.me : (sibling.contact?.name ?? '');
    final linkedPayable = sibling.linkedPayable;
    final linkedReceivable = sibling.linkedReceivable;
    final isSettled = (linkedPayable?.status == 'PAID') || (linkedReceivable?.status == 'RECEIVED');
    final settledLineLabel =
        splitShareSettledStatusLabel(l10n, linkedPayable, linkedReceivable);
    final canMarkPaid = linkedPayable != null && linkedPayable.status == 'PENDING';
    final canMarkReceived = linkedReceivable != null && linkedReceivable.status == 'PENDING';

    return Padding(
      padding: const EdgeInsets.only(bottom: 12),
      child: Material(
        color: theme.colorScheme.surfaceContainerHighest.withValues(alpha: 0.6),
        borderRadius: BorderRadius.circular(16),
        clipBehavior: Clip.antiAlias,
        child: InkWell(
          onTap: () {
            Navigator.push(
              context,
              MaterialPageRoute(
                builder: (context) => TransactionDetailsDialog(
                  transactionUuid: sibling.transaction.uuid,
                ),
              ),
            );
          },
          child: Container(
            padding: const EdgeInsets.all(16),
            decoration: BoxDecoration(
              borderRadius: BorderRadius.circular(16),
              border: Border.all(
                color: isSettled ? theme.colorScheme.primary.withValues(alpha: 0.6) : theme.dividerColor,
              ),
            ),
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Row(
                  children: [
                    CircleAvatar(
                      radius: 18,
                      backgroundColor: AppColors.getContactColor(label).withValues(alpha: 0.2),
                      child: Text(
                        label.isNotEmpty ? label[0].toUpperCase() : '?',
                        style: const TextStyle(fontWeight: FontWeight.bold),
                      ),
                    ),
                    const SizedBox(width: 12),
                    Expanded(
                      child: Column(
                        crossAxisAlignment: CrossAxisAlignment.start,
                        children: [
                          Text(
                            label,
                            style: theme.textTheme.bodyLarge?.copyWith(fontWeight: FontWeight.w600),
                          ),
                          if (settledLineLabel != null) ...[
                            const SizedBox(height: 2),
                            Text(
                              settledLineLabel,
                              style: theme.textTheme.bodySmall?.copyWith(color: theme.colorScheme.primary),
                            ),
                          ],
                        ],
                      ),
                    ),
                    Text(
                      AmountFormatter.formatWithCurrency(
                        sibling.transaction.amount,
                        currency.symbol,
                        currency.decimalPlaces,
                      ),
                      style: theme.textTheme.bodyLarge?.copyWith(fontWeight: FontWeight.bold),
                    ),
                  ],
                ),
                if (canMarkPaid || canMarkReceived) ...[
                  const SizedBox(height: 16),
                  SizedBox(
                    width: double.infinity,
                    child: FilledButton.icon(
                      onPressed: () async {
                        if (canMarkPaid) {
                          await TransactionDetailsDialog.markAsPaid(context, ref, linkedPayable.uuid, sibling);
                        } else if (canMarkReceived) {
                          await TransactionDetailsDialog.markAsReceived(context, ref, linkedReceivable.uuid, sibling);
                        }
                      },
                      icon: const Icon(Icons.check_circle),
                      label: Text(canMarkPaid ? l10n.markAsPaid : l10n.markAsReceived),
                      style: canMarkPaid
                          ? AppColors.transactionMarkAsPaidFilledStyle()
                          : AppColors.transactionMarkAsReceivedFilledStyle(),
                    ),
                  ),
                ],
              ],
            ),
          ),
        ),
      ),
    );
  }
}
