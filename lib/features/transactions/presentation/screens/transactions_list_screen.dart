class TransactionsListScreen extends ConsumerWidget {
  const TransactionsListScreen({super.key});

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final l10n = AppLocalizations.of(context)!;
    // Use the new provider with ALL details (category + contact)
    final transactionsAsync = ref.watch(transactionsWithDetailsProvider);
    final theme = Theme.of(context);

    return Scaffold(
      appBar: AppBar(
        title: Text(l10n.transactions),
        actions: [
          IconButton(
            icon: const Icon(Icons.filter_list),
            onPressed: () {
              // TODO: Implement filter
            },
          ),
          IconButton(
            icon: const Icon(Icons.search),
            onPressed: () {
              // TODO: Implement search
            },
          ),
        ],
      ),
      body: transactionsAsync.when(
        data: (transactions) {
          if (transactions.isEmpty) {
            return Center(
              child: Column(
                mainAxisAlignment: MainAxisAlignment.center,
                children: [
                  Icon(
                    Icons.receipt_long_outlined,
                    size: 120,
                    color: Colors.grey[300],
                  ),
                  const SizedBox(height: 24),
                  Text(
                    'No transactions yet',
                    style: theme.textTheme.titleLarge?.copyWith(
                      color: Colors.grey[600],
                      fontWeight: FontWeight.w600,
                    ),
                  ),
                  const SizedBox(height: 12),
                  Text(
                    'Tap + to add your first transaction',
                    style: theme.textTheme.bodyMedium?.copyWith(
                      color: Colors.grey[500],
                    ),
                  ),
                ],
              ),
            );
          }

          // Group transactions by date
          final groupedTransactions = <String, List>{};
          for (final item in transactions) {
            final dateKey = DateFormat.yMMMd().format(item.transaction.date);
            groupedTransactions.putIfAbsent(dateKey, () => []);
            groupedTransactions[dateKey]!.add(item);
          }

          final service = ref.read(transactionServiceProvider);

          return ListView.builder(
            padding: const EdgeInsets.only(bottom: 80),
            itemCount: groupedTransactions.length,
            itemBuilder: (context, index) {
              final dateKey = groupedTransactions.keys.elementAt(index);
              final dateTransactions = groupedTransactions[dateKey]!;

              return Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  // Date Header
                  Padding(
                    padding: const EdgeInsets.fromLTRB(16, 16, 16, 8),
                    child: Text(
                      dateKey,
                      style: theme.textTheme.titleSmall?.copyWith(
                        color: theme.colorScheme.onSurfaceVariant,
                        fontWeight: FontWeight.w600,
                      ),
                    ),
                  ),

                  // Transactions for this date
                  ...dateTransactions.map((item) {
                    final isExpense = item.transaction.type == 'EXPENSE';
                    
                    // Determine if transaction is restricted from editing/deleting
                    final isRestricted = item.transaction.isAutoGenerated == true || 
                                        item.isLinkedEntryMarked;

                    return Padding(
                      padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 6),
                      child: SwipeableListItem(
                        enableEdit: !isRestricted,
                        enableDelete: !isRestricted,
                        borderRadius: 20,
                        onEdit: isRestricted ? null : () {
                          Navigator.push(
                            context,
                            MaterialPageRoute(
                              builder: (context) => EditTransactionScreen(
                                transaction: item.transaction,
                                category: item.category,
                                contact: item.contact,
                              ),
                            ),
                          );
                        },
                        onDelete: isRestricted ? null : () async {
                          try {
                            await service.deleteTransaction(item.transaction.id);
                            if (context.mounted) {
                              ToastUtils.showSuccessToast(context, 'Transaction deleted');
                            }
                          } catch (e) {
                            if (context.mounted) {
                              ToastUtils.showErrorToast(context, 'Error deleting transaction: $e');
                            }
                          }
                        },
                        child: _buildTransactionCard(
                          context,
                          ref: ref,
                          item: item,
                          isExpense: isExpense,
                        ),
                      ),
                    );
                  }),
                ],
              );
            },
          );
        },
        loading: () => const Center(child: CircularProgressIndicator()),
        error: (error, stack) => Center(
          child: Column(
            mainAxisAlignment: MainAxisAlignment.center,
            children: [
              const Icon(Icons.error_outline, size: 60, color: Colors.red),
              const SizedBox(height: 16),
              Text(
                'Error loading transactions',
                style: theme.textTheme.titleLarge,
              ),
              const SizedBox(height: 8),
              Text(
                error.toString(),
                style: theme.textTheme.bodySmall,
                textAlign: TextAlign.center,
              ),
            ],
          ),
        ),
      ),
      floatingActionButton: FloatingActionButton(
        onPressed: () {
          Navigator.push(
            context,
            MaterialPageRoute(
              builder: (context) => const AddTransactionScreen(),
            ),
          );
        },
        backgroundColor: AppColors.transactionsSectionColor,
        foregroundColor: Colors.white,
        child: const Icon(Icons.add),
      ),
    );
  }

  Widget _buildTransactionCard(
    BuildContext context, {
    required WidgetRef ref,
    required dynamic item, // TransactionWithDetails
    required bool isExpense,
  }) {
    final theme = Theme.of(context);
    final currency = ref.watch(currentCurrencyProvider).value;
    final isDark = theme.brightness == Brightness.dark;
    
    if (currency == null) {
      return const SizedBox.shrink();
    }
    final transaction = item.transaction;
    final category = item.category;
    final contact = item.contact;

    // Check if it's an "inactive" transaction (Paid BY or Will Receive that hasn't been marked yet)
    final isInactive = (transaction.paidRelationship == 'PAID_BY' || 
                       transaction.paidRelationship == 'WILL_RECEIVE') &&
                       !item.isLinkedEntryMarked;

    // Resolve category color and icon
    Color categoryColor;
    if (category?.color != null) {
      try {
        categoryColor =
            Color(int.parse(category!.color!.replaceAll('#', '0xFF')));
      } catch (_) {
        categoryColor =
            isExpense ? AppColors.expenseColor : AppColors.incomeColor;
      }
    } else {
      categoryColor =
          isExpense ? AppColors.expenseColor : AppColors.incomeColor;
    }

    // Apply dull effect if inactive
    final displayColor = isInactive ? categoryColor.withValues(alpha: 0.5) : categoryColor;
    final textColor = isInactive ? theme.colorScheme.onSurface.withValues(alpha: 0.6) : theme.colorScheme.onSurface;

    // Dynamic font size based on amount
    final amountFontSize = AmountFormatter.getFontSize(transaction.amount);

    return Container(
      decoration: BoxDecoration(
        color: theme.cardColor.withValues(alpha: isInactive ? 0.6 : 1.0),
        borderRadius: BorderRadius.circular(20),
        border: Border.all(
          color: displayColor.withValues(alpha: isDark ? 0.2 : 0.1),
          width: 1,
        ),
        boxShadow: [
          BoxShadow(
            color: displayColor.withValues(alpha: isDark ? 0.05 : 0.08),
            blurRadius: isInactive ? 4 : 12,
            offset: const Offset(0, 4),
          ),
        ],
      ),
      child: ListTile(
        contentPadding: const EdgeInsets.all(16),
        leading: Container(
          width: 50,
          height: 50,
          decoration: BoxDecoration(
            color: displayColor.withValues(alpha: 0.1),
            borderRadius: BorderRadius.circular(14),
            border: Border.all(
              color: displayColor.withValues(alpha: 0.3),
              width: 1,
            ),
          ),
          alignment: Alignment.center,
          child: _buildCategoryIcon(category?.icon, displayColor, isExpense),
        ),
        title: Text(
          transaction.description ?? (isExpense ? 'Expense' : 'Income'),
          style: theme.textTheme.titleMedium?.copyWith(
            fontWeight: FontWeight.w600,
            color: textColor,
            decoration: isInactive ? null : null, // Could add strikethrough if cancelled
          ),
        ),
        subtitle: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Text(
              category?.name ?? 'Uncategorized',
              style: theme.textTheme.bodySmall?.copyWith(
                color: theme.colorScheme.onSurfaceVariant.withValues(alpha: isInactive ? 0.5 : 1.0),
              ),
              overflow: TextOverflow.ellipsis,
            ),
            // Contact tag - styled like payable/receivable tags
            if (contact != null) ...[
              const SizedBox(height: 6),
              Container(
                padding: const EdgeInsets.symmetric(horizontal: 6, vertical: 3),
                decoration: BoxDecoration(
                  color: AppColors.getContactColor(contact.name).withValues(alpha: 0.1),
                  borderRadius: BorderRadius.circular(4),
                  border: Border.all(
                    color: AppColors.getContactColor(contact.name).withValues(alpha: 0.3),
                    width: 1,
                  ),
                ),
                child: Row(
                  mainAxisSize: MainAxisSize.min,
                  children: [
                    Container(
                      width: 14,
                      height: 14,
                      decoration: BoxDecoration(
                        gradient: AppColors.getContactGradient(contact.name),
                        shape: BoxShape.circle,
                      ),
                      alignment: Alignment.center,
                      child: Text(
                        contact.name.isNotEmpty ? contact.name[0].toUpperCase() : '?',
                        style: const TextStyle(
                          color: Colors.white,
                          fontSize: 7,
                          fontWeight: FontWeight.bold,
                        ),
                      ),
                    ),
                    const SizedBox(width: 4),
                    Flexible(
                      child: Text(
                        contact.name,
                        style: TextStyle(
                          fontSize: 10,
                          color: theme.colorScheme.onSurfaceVariant,
                          fontWeight: FontWeight.w600,
                        ),
                        overflow: TextOverflow.ellipsis,
                      ),
                    ),
                  ],
                ),
              ),
            ],
          ],
        ),
        trailing: Column(
          mainAxisAlignment: MainAxisAlignment.center,
          crossAxisAlignment: CrossAxisAlignment.end,
          children: [
            Text(
                          '${isExpense ? '-' : '+'} ${AmountFormatter.formatWithCurrency(transaction.amount, currency.symbol, currency.decimalPlaces)}',
              style: theme.textTheme.titleLarge?.copyWith(
                color: isExpense 
                    ? (isInactive ? AppColors.expenseColor.withValues(alpha: 0.5) : AppColors.expenseColor)
                    : (isInactive ? AppColors.incomeColor.withValues(alpha: 0.5) : AppColors.incomeColor),
                fontWeight: FontWeight.bold,
                fontSize: amountFontSize,
              ),
            ),
            // Show status badge below amount for linked transactions
            if (transaction.paidRelationship != null) ...[
              const SizedBox(height: 4),
              Container(
                padding: const EdgeInsets.symmetric(horizontal: 6, vertical: 2),
                decoration: BoxDecoration(
                  color: _getStatusColor(transaction.paidRelationship!).withValues(alpha: 0.1),
                  borderRadius: BorderRadius.circular(4),
                  border: Border.all(
                    color: _getStatusColor(transaction.paidRelationship!).withValues(alpha: 0.3),
                    width: 1,
                  ),
                ),
                child: Row(
                  mainAxisSize: MainAxisSize.min,
                  children: [
                    if (item.isLinkedEntryMarked) ...[
                      Icon(
                        Icons.check_circle,
                        size: 10,
                        color: _getStatusColor(transaction.paidRelationship!),
                      ),
                      const SizedBox(width: 3),
                    ],
                    Text(
                      _getStatusLabel(transaction.paidRelationship!, item.isLinkedEntryMarked),
                      style: TextStyle(
                        fontSize: 10,
                        color: _getStatusColor(transaction.paidRelationship!),
                        fontWeight: FontWeight.bold,
                      ),
                    ),
                  ],
                ),
              ),
            ],
            // Show "Auto" badge for auto-generated transactions
            if (transaction.isAutoGenerated == true) ...[
              const SizedBox(height: 4),
              Container(
                padding: const EdgeInsets.symmetric(horizontal: 6, vertical: 2),
                decoration: BoxDecoration(
                  color: Colors.grey.withValues(alpha: 0.1),
                  borderRadius: BorderRadius.circular(4),
                  border: Border.all(
                    color: Colors.grey.withValues(alpha: 0.3),
                    width: 1,
                  ),
                ),
                child: Row(
                  mainAxisSize: MainAxisSize.min,
                  children: [
                    Icon(
                      Icons.auto_awesome,
                      size: 10,
                      color: Colors.grey[600],
                    ),
                    const SizedBox(width: 3),
                    Text(
                      'Auto',
                      style: TextStyle(
                        fontSize: 10,
                        color: Colors.grey[600],
                        fontWeight: FontWeight.bold,
                      ),
                    ),
                  ],
                ),
              ),
            ],
          ],
        ),
        onTap: () {
          Navigator.push(
            context,
            MaterialPageRoute(
              builder: (context) => TransactionDetailsDialog(item: item),
            ),
          );
        },
      ),
    );
  }

  Widget _buildCategoryIcon(String? iconString, Color color, bool isExpense) {
    if (iconString == null) {
      return Icon(
        isExpense ? Icons.money_off : Icons.attach_money,
        color: color,
        size: 24,
      );
    }

    // Try to parse as integer (code point for IconData)
    final int? codePoint = int.tryParse(iconString);
    if (codePoint != null) {
      return Icon(
        IconData(codePoint, fontFamily: 'MaterialIcons'),
        color: color,
        size: 24,
      );
    }

    // Fallback to text (emoji)
    return Text(
      iconString,
      style: const TextStyle(fontSize: 24),
    );
  }

  Color _getStatusColor(String relationship) {
    switch (relationship) {
      case 'PAID_FOR':
        return AppColors.receivableColor;
      case 'PAID_BY':
        return AppColors.payableColor;
      case 'RECEIVED_FROM':
        return AppColors.payableColor;
      case 'WILL_RECEIVE':
        return AppColors.receivableColor;
      default:
        return Colors.grey;
    }
  }

  String _getStatusLabel(String relationship, bool isMarked) {
    switch (relationship) {
      case 'PAID_FOR':
        return isMarked ? 'Received' : 'Receivable';
      case 'PAID_BY':
        return isMarked ? 'Paid' : 'Payable';
      case 'RECEIVED_FROM':
        return isMarked ? 'Paid' : 'Payable';
      case 'WILL_RECEIVE':
        return isMarked ? 'Received' : 'Receivable';
      default:
        return '';
    }
  }
}
