  String _getStatusLabel(
      BuildContext context, String relationship, bool isMarked) {
    final l10n = AppLocalizations.of(context)!;
    switch (relationship.toLowerCase()) {
      case 'paid_for':
        return isMarked ? l10n.receivedTag : l10n.receivableTag;
      case 'paid_by':
        return isMarked ? l10n.paidTag : l10n.payableTag;
      case 'received_from':
        return isMarked ? l10n.paidTag : l10n.payableTag;
      case 'will_receive':
        return isMarked ? l10n.receivedTag : l10n.receivableTag;
      default:
        return '';
    }
  }

  Future<void> _deleteTransaction(
      BuildContext context, WidgetRef ref, String transactionUuid) async {
    final l10n = AppLocalizations.of(context)!;
    final confirmed = await showDialog<bool>(
      context: context,
      builder: (context) => AlertDialog(
        title: Text(l10n.deleteTransactionTitle),
        content: Text(l10n.deleteTransactionMessage),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(context, false),
            child: Text(l10n.cancel),
          ),
          FilledButton(
            onPressed: () => Navigator.pop(context, true),
            style: FilledButton.styleFrom(backgroundColor: Colors.red),
            child: Text(l10n.delete),
          ),
        ],
      ),
    );

    if (confirmed == true && context.mounted) {
      try {
        final service = ref.read(transactionServiceProvider);
        await service.deleteTransaction(transactionUuid);

        if (context.mounted) {
          Navigator.pop(context);
          ToastUtils.showSuccessToast(
              context, ref, l10n.transactionDeleted);
        }
      } catch (e) {
        if (context.mounted) {
          ToastUtils.showErrorToast(context, ref,
              l10n.errorDeletingTransaction(e.toString()));
        }
      }
    }
  }

