import 'package:url_launcher/url_launcher.dart';
import 'package:intl/intl.dart';

class WhatsAppService {
  /// Send a message via WhatsApp to a phone number
  /// 
  /// [phoneNumber] should be in international format without + (e.g., "919876543210")
  /// [message] is the text to send
  Future<bool> sendMessage(String phoneNumber, String message) async {
    try {
      // Clean phone number (remove spaces, dashes, etc.)
      final cleanNumber = phoneNumber.replaceAll(RegExp(r'[^\d+]'), '');
      
      // WhatsApp URL scheme
      final whatsappUrl = Uri.parse('https://wa.me/$cleanNumber?text=${Uri.encodeComponent(message)}');
      
      if (await canLaunchUrl(whatsappUrl)) {
        await launchUrl(whatsappUrl, mode: LaunchMode.externalApplication);
        return true;
      } else {
        throw Exception('WhatsApp is not installed or phone number is invalid');
      }
    } catch (e) {
      throw Exception('Failed to open WhatsApp: $e');
    }
  }

  /// Format a receivable reminder message
  String formatReceivableReminder({
    required String contactName,
    required double amount,
    required String description,
    DateTime? dueDate,
  }) {
    final buffer = StringBuffer();
    buffer.writeln('Hi $contactName,');
    buffer.writeln();
    buffer.writeln('This is a friendly reminder:');
    buffer.writeln('Amount to receive: ₹${amount.toStringAsFixed(2)}');
    if (description.isNotEmpty) {
      buffer.writeln('For: $description');
    }
    if (dueDate != null) {
      buffer.writeln('Due Date: ${DateFormat.yMMMd().format(dueDate)}');
    }
    buffer.writeln();
    buffer.writeln('Thank you!');
    return buffer.toString();
  }

  /// Format a payable reminder message
  String formatPayableReminder({
    required String contactName,
    required double amount,
    required String description,
    DateTime? dueDate,
  }) {
    final buffer = StringBuffer();
    buffer.writeln('Hi $contactName,');
    buffer.writeln();
    buffer.writeln('Just a reminder:');
    buffer.writeln('Amount I owe you: ₹${amount.toStringAsFixed(2)}');
    if (description.isNotEmpty) {
      buffer.writeln('For: $description');
    }
    if (dueDate != null) {
      buffer.writeln('Due Date: ${DateFormat.yMMMd().format(dueDate)}');
    }
    buffer.writeln();
    buffer.writeln('I will settle this soon. Thanks for your patience!');
    return buffer.toString();
  }

  /// Format a transaction receipt message
  String formatTransactionReceipt({
    required String type,
    required double amount,
    required String description,
    required DateTime date,
    String? categoryName,
    String? contactName,
  }) {
    final buffer = StringBuffer();
    buffer.writeln('📝 Transaction Receipt');
    buffer.writeln();
    buffer.writeln('Type: $type');
    buffer.writeln('Amount: ₹${amount.toStringAsFixed(2)}');
    if (description.isNotEmpty) {
      buffer.writeln('Description: $description');
    }
    if (categoryName != null) {
      buffer.writeln('Category: $categoryName');
    }
    if (contactName != null) {
      buffer.writeln('Contact: $contactName');
    }
    buffer.writeln('Date: ${DateFormat.yMMMd().format(date)}');
    buffer.writeln();
    buffer.writeln('Generated by FlowPaisa 💰');
    return buffer.toString();
  }
}

